-- loaddata.sql : populate the DIST400 sample application
-- Run with: RUNSQLSTM SRCSTMF('.../data/loaddata.sql') COMMIT(*NONE) NAMING(*SYS) DFTRDBCOL(DIST400)
-- Deterministic (no RANDOM) so every build produces the same rows and counts:
--   CUSTMAST 400   ITEMMAST 2,500   INVBAL 2,500   PRICELST 10,000   SUBITEM 300
--   CONTRACT 1,850   ORDHDR 9,720   ORDDTL 48,600
-- Seeded rows the lab guide depends on:
--   customer 100230 LAKESIDE DINER, item 201410 TOMATO DICED CND 6/#10,
--   contract 100230/201410 at 42.50 effective 260101 to 261231.

DELETE FROM ORDDTL;  DELETE FROM ORDHDR;  DELETE FROM CONTRACT;  DELETE FROM PRICELST;
DELETE FROM SUBITEM; DELETE FROM INVBAL;  DELETE FROM ITEMMAST;  DELETE FROM CUSTMAST;

-- ---------------------------------------------------------------- customers (400)
INSERT INTO CUSTMAST (CUSTNO, CNAME, CADDR, CCITY, CSTATE, CROUTE, CSTOP, PCLASS, DLVDAY, CSTAT)
WITH n (i) AS (SELECT 1 FROM SYSIBM.SYSDUMMY1 UNION ALL SELECT i + 1 FROM n WHERE i < 400)
SELECT 100000 + i,
       CASE MOD(i, 20) WHEN 0 THEN 'HARBOR' WHEN 1 THEN 'MAPLE STREET' WHEN 2 THEN 'RIVERSIDE' WHEN 3 THEN 'OAKWOOD'
                       WHEN 4 THEN 'SUNRISE' WHEN 5 THEN 'BLUE RIDGE' WHEN 6 THEN 'PARKVIEW' WHEN 7 THEN 'HILLTOP'
                       WHEN 8 THEN 'WESTGATE' WHEN 9 THEN 'CEDAR GROVE' WHEN 10 THEN 'MAIN STREET' WHEN 11 THEN 'LAKEVIEW'
                       WHEN 12 THEN 'PRAIRIE' WHEN 13 THEN 'SOUTHSIDE' WHEN 14 THEN 'NORTH PARK' WHEN 15 THEN 'BAYSIDE'
                       WHEN 16 THEN 'PINEWOOD' WHEN 17 THEN 'FAIRVIEW' WHEN 18 THEN 'ELMWOOD' ELSE 'GRANITE' END
       || ' ' ||
       CASE MOD(i, 10) WHEN 0 THEN 'ELEMENTARY SCHOOL' WHEN 1 THEN 'MEDICAL CENTER' WHEN 2 THEN 'GRILL'
                       WHEN 3 THEN 'CAFE' WHEN 4 THEN 'PIZZERIA' WHEN 5 THEN 'STEAKHOUSE' WHEN 6 THEN 'DINER'
                       WHEN 7 THEN 'TAQUERIA' WHEN 8 THEN 'BISTRO' ELSE 'CATERING' END,
       RTRIM(CHAR(100 + MOD(i * 37, 8900))) || ' ' ||
       CASE MOD(i, 5) WHEN 0 THEN 'INDUSTRIAL BLVD' WHEN 1 THEN 'MAIN ST' WHEN 2 THEN 'COMMERCE DR' WHEN 3 THEN 'MARKET AVE' ELSE 'HIGHWAY 6' END,
       CASE MOD(i, 8) WHEN 0 THEN 'HOUSTON' WHEN 1 THEN 'DALLAS' WHEN 2 THEN 'AUSTIN' WHEN 3 THEN 'SAN ANTONIO'
                      WHEN 4 THEN 'FORT WORTH' WHEN 5 THEN 'EL PASO' WHEN 6 THEN 'WACO' ELSE 'LUBBOCK' END,
       'TX',
       1 + MOD(i, 20),                 -- route 1..20
       1 + (i - 1) / 20,               -- stop 1..20 within the route
       CASE MOD(i, 10) WHEN 0 THEN 'S' WHEN 1 THEN 'H' ELSE 'R' END,
       CASE MOD(i, 3) WHEN 0 THEN 'YNYNYNN' WHEN 1 THEN 'NYNYNYN' ELSE 'YYYYYNN' END,
       'A'
FROM n;
UPDATE CUSTMAST SET CNAME = 'LAKESIDE DINER', CADDR = '4120 SHORELINE DR', CCITY = 'AUSTIN', PCLASS = 'R'
 WHERE CUSTNO = 100230;

-- ---------------------------------------------------------------- items (2,500)
INSERT INTO ITEMMAST (ITEMNO, IDESC, IPACK, IBRAND, ICATEG, IZONE, CWFLAG, AVGWGT, UNITPK, SHELFL)
WITH n (i) AS (SELECT 1 FROM SYSIBM.SYSDUMMY1 UNION ALL SELECT i + 1 FROM n WHERE i < 2500),
     b AS (SELECT i, MOD(i, 25) AS p FROM n)
SELECT 200000 + i,
       CASE p WHEN 0 THEN 'CHICKEN BREAST BNLS SKNLS' WHEN 1 THEN 'BEEF GROUND 80/20' WHEN 2 THEN 'PORK LOIN BNLS'
              WHEN 3 THEN 'CHEESE CHEDDAR BLOCK' WHEN 4 THEN 'BACON SLICED 14/18' WHEN 5 THEN 'TURKEY BREAST RSTD'
              WHEN 6 THEN 'SALMON FILLET ATLANTIC' WHEN 7 THEN 'TOMATO DICED CND' WHEN 8 THEN 'OIL CANOLA FRY'
              WHEN 9 THEN 'FLOUR ALL PURPOSE' WHEN 10 THEN 'RICE LONG GRAIN' WHEN 11 THEN 'SUGAR GRANULATED'
              WHEN 12 THEN 'PASTA PENNE' WHEN 13 THEN 'KETCHUP POUCH' WHEN 14 THEN 'FRIES SHOESTRING FRZ'
              WHEN 15 THEN 'BROCCOLI FLORETS FRZ' WHEN 16 THEN 'ICE CREAM VANILLA' WHEN 17 THEN 'MILK 2 PCT'
              WHEN 18 THEN 'EGGS LARGE' WHEN 19 THEN 'BUTTER SOLIDS' WHEN 20 THEN 'LETTUCE ROMAINE HEARTS'
              WHEN 21 THEN 'TOMATO 5X6' WHEN 22 THEN 'ONION YELLOW JUMBO' WHEN 23 THEN 'CUP FOAM 16 OZ' ELSE 'GLOVES VINYL LG' END
       || ' ' || CASE MOD(i / 25, 4) WHEN 0 THEN 'A' WHEN 1 THEN 'B' WHEN 2 THEN 'C' ELSE 'D' END,
       CASE p WHEN 0 THEN '4/10 LB' WHEN 1 THEN '8/10 LB' WHEN 2 THEN '6/8 LB' WHEN 3 THEN '2/20 LB' WHEN 4 THEN '15 LB'
              WHEN 5 THEN '2/12 LB' WHEN 6 THEN '10 LB' WHEN 7 THEN '6/#10' WHEN 8 THEN '35 LB' WHEN 9 THEN '50 LB'
              WHEN 10 THEN '50 LB' WHEN 11 THEN '50 LB' WHEN 12 THEN '2/10 LB' WHEN 13 THEN '3 GAL' WHEN 14 THEN '6/5 LB'
              WHEN 15 THEN '12/2 LB' WHEN 16 THEN '3 GAL' WHEN 17 THEN '4/1 GAL' WHEN 18 THEN '15 DZ' WHEN 19 THEN '36/1 LB'
              WHEN 20 THEN '12 CT' WHEN 21 THEN '25 LB' WHEN 22 THEN '50 LB' WHEN 23 THEN '1000 CT' ELSE '10/100 CT' END,
       CASE MOD(i, 6) WHEN 0 THEN 'HOUSE' WHEN 1 THEN 'PREMIER' WHEN 2 THEN 'CLASSIC' WHEN 3 THEN 'PACKER' WHEN 4 THEN 'IMPERIAL' ELSE 'RELIANCE' END,
       CASE WHEN p <= 6 THEN 'PRO' WHEN p <= 13 THEN 'DRY' WHEN p <= 16 THEN 'FRZ' WHEN p <= 19 THEN 'DAI' WHEN p <= 22 THEN 'PRD' ELSE 'NFD' END,
       CASE WHEN p <= 6 THEN 'C' WHEN p <= 13 THEN 'D' WHEN p <= 16 THEN 'F' WHEN p <= 22 THEN 'C' ELSE 'D' END,
       CASE WHEN p <= 6 THEN 'Y' ELSE 'N' END,
       CASE WHEN p <= 6 THEN 20 + MOD(i, 30) + MOD(i, 7) / 10.0 ELSE 0 END,
       CASE p WHEN 7 THEN 6 WHEN 14 THEN 6 WHEN 15 THEN 12 WHEN 18 THEN 15 WHEN 19 THEN 36 WHEN 20 THEN 12 WHEN 23 THEN 1000 WHEN 24 THEN 1000 ELSE 1 END,
       CASE WHEN p <= 6 THEN 14 WHEN p <= 13 THEN 365 WHEN p <= 16 THEN 180 WHEN p <= 19 THEN 21 WHEN p <= 22 THEN 7 ELSE 999 END
FROM b;
UPDATE ITEMMAST SET IDESC = 'TOMATO DICED CND 6/#10', IPACK = '6/#10', IBRAND = 'HOUSE', ICATEG = 'DRY', IZONE = 'D',
       CWFLAG = 'N', AVGWGT = 0, UNITPK = 6, SHELFL = 365
 WHERE ITEMNO = 201410;

-- ---------------------------------------------------------------- inventory (2,500), a few items short
INSERT INTO INVBAL (IWHSE, IITEM, ONHAND, ALLOC)
SELECT '01', ITEMNO, CASE WHEN MOD(ITEMNO, 37) = 0 THEN 0 ELSE 20 + MOD(ITEMNO * 7919, 480) END, 0 FROM ITEMMAST;

-- ---------------------------------------------------------------- price list (4 classes x 2,500)
INSERT INTO PRICELST (PITEM, PCLASS, LPRICE)
WITH base AS (SELECT ITEMNO, 10 + MOD(ITEMNO * 31, 90) + MOD(ITEMNO, 100) / 100.0 AS LP FROM ITEMMAST)
SELECT ITEMNO, '0', LP FROM base UNION ALL
SELECT ITEMNO, 'R', ROUND(LP * 0.97, 2) FROM base UNION ALL
SELECT ITEMNO, 'S', ROUND(LP * 0.95, 2) FROM base UNION ALL
SELECT ITEMNO, 'H', ROUND(LP * 0.96, 2) FROM base;

-- ---------------------------------------------------------------- substitutes (300)
INSERT INTO SUBITEM (SITEM, SSUB)
WITH n (i) AS (SELECT 1 FROM SYSIBM.SYSDUMMY1 UNION ALL SELECT i + 1 FROM n WHERE i < 300)
SELECT 200000 + i * 8, 200000 + i * 8 + 25 FROM n;

-- ---------------------------------------------------------------- contracts (1,849 generated + 1 seeded)
-- MOD(i,40)=0 rows are expired last year. MOD(i,185)=0 rows were keyed with the shop's
-- "no expiry" convention 991231, which the Y2K window in OE005 reads as 1999: they price at list.
INSERT INTO CONTRACT (CCUST, CITEM, CPRICE, CEFFDT, CEXPDT)
WITH n (i) AS (SELECT 1 FROM SYSIBM.SYSDUMMY1 UNION ALL SELECT i + 1 FROM n WHERE i < 1849),
     g AS (SELECT i, 100001 + MOD(i * 37, 400) AS cu, 200001 + MOD(i * 131, 2500) AS it FROM n)
SELECT g.cu, g.it, ROUND(p.LPRICE * 0.90, 2),
       CASE WHEN MOD(i, 40) = 0 THEN 250101 ELSE 260101 END,
       CASE WHEN MOD(i, 40) = 0 THEN 251231 WHEN MOD(i, 185) = 0 THEN 991231 ELSE 261231 END
FROM g JOIN PRICELST p ON p.PITEM = g.it AND p.PCLASS = '0'
WHERE NOT (g.cu = 100230 AND g.it = 201410);
INSERT INTO CONTRACT (CCUST, CITEM, CPRICE, CEFFDT, CEXPDT) VALUES (100230, 201410, 42.50, 260101, 261231);

-- ---------------------------------------------------------------- orders (9,720 over 72 delivery days)
INSERT INTO ORDHDR (ORDNO, OCUST, ODLVDT, OROUTE, OSTOP, OSTAT, OENTDT, OENTBY)
WITH n (i) AS (SELECT 1 FROM SYSIBM.SYSDUMMY1 UNION ALL SELECT i + 1 FROM n WHERE i < 9720),
     o AS (SELECT i, 100001 + MOD(i * 13, 400) AS cu, DATE('2026-08-10') + MOD(i, 72) DAYS AS d FROM n)
SELECT i, cu,
       MOD(YEAR(d), 100) * 10000 + MONTH(d) * 100 + DAY(d),
       c.CROUTE, c.CSTOP,
       CASE WHEN d >= DATE('2026-10-07') THEN 'O' ELSE 'R' END,
       MOD(YEAR(d - 1 DAY), 100) * 10000 + MONTH(d - 1 DAY) * 100 + DAY(d - 1 DAY),
       CASE MOD(i, 4) WHEN 0 THEN 'JPEREZ' WHEN 1 THEN 'MCHEN' WHEN 2 THEN 'WEBORDER' ELSE 'RSMITH' END
FROM o JOIN CUSTMAST c ON c.CUSTNO = o.cu;

-- ---------------------------------------------------------------- order lines (5 per order)
INSERT INTO ORDDTL (DORDNO, DLINE, DITEM, QTYORD, QTYSHP, CWGHT, UPRICE, PSRC, SUBFLG, DOITEM)
WITH l (ln) AS (SELECT 1 FROM SYSIBM.SYSDUMMY1 UNION ALL SELECT ln + 1 FROM l WHERE ln < 5),
     x AS (SELECT h.ORDNO, h.OSTAT, l.ln, 200001 + MOD(h.ORDNO * 17 + l.ln * 523, 2500) AS it,
                  1 + MOD(h.ORDNO + l.ln, 12) AS q FROM ORDHDR h CROSS JOIN l)
SELECT x.ORDNO, x.ln, x.it, x.q,
       CASE WHEN x.OSTAT = 'R' THEN x.q ELSE 0 END,
       CASE WHEN x.OSTAT = 'R' AND i.CWFLAG = 'Y' THEN ROUND(i.AVGWGT * x.q * 1.02, 2) ELSE 0 END,
       CASE WHEN i.CWFLAG = 'Y' THEN ROUND(p.LPRICE * i.AVGWGT, 2) ELSE p.LPRICE END,
       'L', ' ', 0
FROM x JOIN ITEMMAST i ON i.ITEMNO = x.it JOIN PRICELST p ON p.PITEM = x.it AND p.PCLASS = '0';

